export type HttpMethod = "get" | "post" | "put" | "patch" | "delete";

/** Who may call a route. Authority always comes from the verified token plus the database. */
export type RouteAccess =
  | { kind: "public" }
  | { kind: "signed_in" }
  | { kind: "merchant"; note: string }
  | { kind: "admin"; roles: readonly string[] };

export interface RouteContract {
  method: HttpMethod;
  /** OpenAPI path template, for example `/v1/merchant/branches/{id}`. */
  path: string;
  operationId: string;
  summary: string;
  tag: string;
  access: RouteAccess;
  /** Route requires an `Idempotency-Key` header (docs/07 conventions). */
  idempotent?: boolean;
  params?: z.ZodObject;
  query?: z.ZodObject;
  body?: z.ZodType;
  /** Raw (non-JSON) request body, with the accepted media types. */
  rawBody?: readonly string[];
  /**
   * Success status and body: a JSON schema, `binary` for a file download, or `eventStream`
   * for server-sent events whose `data` lines match the schema.
   */
  success:
    | { status: number; schema: z.ZodType }
    | { status: number; binary: true }
    | { status: number; eventStream: z.ZodType };
  /** Error statuses this route can return, besides 500. */
  errors: number[];
}

